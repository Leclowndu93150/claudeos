#define KB_BUF 256
static uint8_t kb_buf[KB_BUF];
static int kb_head = 0, kb_tail = 0;
static KeyboardState kb_state;

static bool kb_extended = false;

static void kb_wait_write(void) {
    int t = 100000;
    while (t-- && (inb(0x64) & 2));
}

void keyboard_init(void) {
    k_memset(&kb_state, 0, sizeof(kb_state));
    while (inb(0x64) & 1) inb(0x60);

    kb_wait_write(); outb(0x64, 0x20);
    int t = 100000;
    while (t-- && !(inb(0x64) & 1));
    uint8_t cfg = inb(0x60);
    cfg |= 0x01;
    cfg |= 0x40;
    kb_wait_write(); outb(0x64, 0x60);
    kb_wait_write(); outb(0x60, cfg);

    kb_wait_write(); outb(0x64, 0xAE);

    kb_wait_write(); outb(0x60, 0xF4);
    t = 100000;
    while (t-- && !(inb(0x64) & 1));
    inb(0x60);
}

void keyboard_irq(void) {
    uint8_t sc = inb(0x60);

    if (sc == 0xE0) { kb_extended = true; return; }

    bool released = sc & 0x80;
    uint8_t key = sc & 0x7F;
    uint8_t evcode = key;

    if (kb_extended) {
        kb_extended = false;
        if (key == 0x48) evcode = 0x48;
        else if (key == 0x50) evcode = 0x50;
        else if (key == 0x4B) evcode = 0x4B;
        else if (key == 0x4D) evcode = 0x4D;
        else if (key == 0x1D) { kb_state.ctrl = !released; return; }
        else if (key == 0x38) { kb_state.alt = !released; return; }
        else return;

        if (!released) {
            Event ev;
            k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_KEY_DOWN;
            ev.keycode = evcode;
            ev.key_char = 0;
            ev.shift = kb_state.shift;
            ev.ctrl = kb_state.ctrl;
            ev.alt = kb_state.alt;
            event_push(&ev);
        }
        return;
    }

    if (key == 0x2A || key == 0x36) { kb_state.shift = !released; return; }
    if (key == 0x1D) { kb_state.ctrl = !released; return; }
    if (key == 0x38) { kb_state.alt = !released; return; }
    if (key == 0x3A && !released) { kb_state.caps = !kb_state.caps; return; }

    if (!released && key < sizeof(sc_ascii)) {
        char ch;
        bool upper = kb_state.shift ^ kb_state.caps;
        if (upper) ch = sc_shift[key];
        else ch = sc_ascii[key];

        Event ev;
        k_memset(&ev, 0, sizeof(ev));
        ev.type = EVENT_KEY_DOWN;
        ev.keycode = key;
        ev.key_char = ch;
        ev.shift = kb_state.shift;
        ev.ctrl = kb_state.ctrl;
        ev.alt = kb_state.alt;
        event_push(&ev);

        int next = (kb_head + 1) % KB_BUF;
        if (next != kb_tail) {
            kb_buf[kb_head] = ch;
            kb_head = next;
        }
    }
}

bool keyboard_has_key(void) { return kb_head != kb_tail; }

int keyboard_getchar(void) {
    if (kb_head == kb_tail) return -1;
    int ch = kb_buf[kb_tail];
    kb_tail = (kb_tail + 1) % KB_BUF;
    return ch;
}

KeyboardState* keyboard_state(void) { return &kb_state; }

static MouseState ms;

static void mouse_wait_write(void) {
    int t = 100000;
    while (t-- && (inb(0x64) & 2));
}

static void mouse_wait_read(void) {
    int t = 100000;
    while (t-- && !(inb(0x64) & 1));
}

static void mouse_cmd(uint8_t cmd) {
    mouse_wait_write(); outb(0x64, 0xD4);
    mouse_wait_write(); outb(0x60, cmd);
    mouse_wait_read();  inb(0x60);
}

void mouse_init(void) {
    k_memset(&ms, 0, sizeof(ms));
    ms.x = 512; ms.y = 384;

    mouse_wait_write(); outb(0x64, 0xA8);
    mouse_wait_write(); outb(0x64, 0x20);
    mouse_wait_read();
    uint8_t status = inb(0x60) | 2;
    mouse_wait_write(); outb(0x64, 0x60);
    mouse_wait_write(); outb(0x60, status);
    mouse_cmd(0xF6);
    mouse_cmd(0xF4);
}

void mouse_irq(void) {
    uint8_t data = inb(0x60);
    switch (ms.cycle) {
    case 0:
        if (data & 0x08) { ms.packet[0] = data; ms.cycle++; }
        break;
    case 1:
        ms.packet[1] = data; ms.cycle++;
        break;
    case 2:
        ms.packet[2] = data; ms.cycle = 0;
        int dx = (int8_t)ms.packet[1];
        int dy = (int8_t)ms.packet[2];
        if (ms.packet[0] & 0x10) dx |= (int)0xFFFFFF00;
        if (ms.packet[0] & 0x20) dy |= (int)0xFFFFFF00;
        int old_x = ms.x, old_y = ms.y;
        ms.x += dx;
        ms.y -= dy;
        Framebuffer* fb = fb_get();
        if (fb) {
            if (ms.x < 0) ms.x = 0;
            if (ms.y < 0) ms.y = 0;
            if (ms.x >= (int)fb->width) ms.x = fb->width - 1;
            if (ms.y >= (int)fb->height) ms.y = fb->height - 1;
        }
        if (ms.x != old_x || ms.y != old_y) {
            Event ev; k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_MOUSE_MOVE;
            ev.mouse_x = ms.x; ev.mouse_y = ms.y;
            event_push(&ev);
        }
        bool nl = ms.packet[0] & 1;
        bool nr = ms.packet[0] & 2;
        if (nl && !ms.left) {
            Event ev; k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_MOUSE_DOWN; ev.mouse_button = 0;
            ev.mouse_x = ms.x; ev.mouse_y = ms.y;
            event_push(&ev);
        }
        if (!nl && ms.left) {
            Event ev; k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_MOUSE_UP; ev.mouse_button = 0;
            ev.mouse_x = ms.x; ev.mouse_y = ms.y;
            event_push(&ev);
        }
        if (nr && !ms.right) {
            Event ev; k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_MOUSE_DOWN; ev.mouse_button = 1;
            ev.mouse_x = ms.x; ev.mouse_y = ms.y;
            event_push(&ev);
        }
        if (!nr && ms.right) {
            Event ev; k_memset(&ev, 0, sizeof(ev));
            ev.type = EVENT_MOUSE_UP; ev.mouse_button = 1;
            ev.mouse_x = ms.x; ev.mouse_y = ms.y;
            event_push(&ev);
        }
        ms.left = nl; ms.right = nr;
        ms.middle = ms.packet[0] & 4;
        break;
    }
}

MouseState* mouse_state(void) { return &ms; }

static Framebuffer fb;
static uint32_t* bb;
static int clip_x, clip_y, clip_w, clip_h;
static bool clipping = false;

void fb_init(uint32_t* addr, uint32_t w, uint32_t h, uint32_t pitch, uint8_t bpp) {
    fb.addr = addr; fb.width = w; fb.height = h;
    fb.pitch = pitch; fb.bpp = bpp;
    bb = (uint32_t*)kmalloc(w * h * 4);
    if (bb) k_memset(bb, 0, w * h * 4);
}

Framebuffer* fb_get(void) { return &fb; }

void fb_clip_set(int x, int y, int w, int h) {
    clip_x = x; clip_y = y; clip_w = w; clip_h = h;
    clipping = true;
}
void fb_clip_reset(void) { clipping = false; }

void fb_pixel(int x, int y, uint32_t c) {
    if (x < 0 || y < 0 || x >= (int)fb.width || y >= (int)fb.height) return;
    if (clipping && (x < clip_x || y < clip_y || x >= clip_x+clip_w || y >= clip_y+clip_h)) return;
    if (bb) bb[y * fb.width + x] = c;
}

void fb_fill(int x, int y, int w, int h, uint32_t c) {
    int x0 = x < 0 ? 0 : x;
    int y0 = y < 0 ? 0 : y;
    int x1 = x+w > (int)fb.width ? (int)fb.width : x+w;
    int y1 = y+h > (int)fb.height ? (int)fb.height : y+h;
    if (clipping) {
        if (x0 < clip_x) x0 = clip_x;
        if (y0 < clip_y) y0 = clip_y;
        if (x1 > clip_x+clip_w) x1 = clip_x+clip_w;
        if (y1 > clip_y+clip_h) y1 = clip_y+clip_h;
    }
    if (!bb) return;
    for (int r = y0; r < y1; r++) {
        uint32_t* p = bb + r * fb.width + x0;
        for (int col = x0; col < x1; col++) *p++ = c;
    }
}

void fb_rect(int x, int y, int w, int h, uint32_t c) {
    fb_fill(x, y, w, 1, c);
    fb_fill(x, y+h-1, w, 1, c);
    fb_fill(x, y, 1, h, c);
    fb_fill(x+w-1, y, 1, h, c);
}

void fb_char(int x, int y, char ch, uint32_t fg, uint32_t bg) {
    if (ch < 32 || ch > 126) ch = '?';
    const uint8_t* g = &font_data[(ch - 32) * FONT_H];
    for (int r = 0; r < FONT_H; r++) {
        uint8_t bits = g[r];
        for (int col = 0; col < FONT_W; col++) {
            fb_pixel(x+col, y+r, (bits & (0x80 >> col)) ? fg : bg);
        }
    }
}

void fb_text(int x, int y, const char* s, uint32_t fg, uint32_t bg) {
    while (*s) { fb_char(x, y, *s, fg, bg); x += FONT_W; s++; }
}

void fb_text_t(int x, int y, const char* s, uint32_t fg) {
    while (*s) {
        if (*s >= 32 && *s <= 126) {
            const uint8_t* g = &font_data[(*s - 32) * FONT_H];
            for (int r = 0; r < FONT_H; r++) {
                uint8_t bits = g[r];
                for (int col = 0; col < FONT_W; col++) {
                    if (bits & (0x80 >> col)) fb_pixel(x+col, y+r, fg);
                }
            }
        }
        x += FONT_W; s++;
    }
}

int fb_text_width(const char* s) { return k_strlen(s) * FONT_W; }

void fb_swap(void) {
    if (!bb || !fb.addr) return;
    for (uint32_t y = 0; y < fb.height; y++) {
        k_memcpy((uint8_t*)fb.addr + y * fb.pitch, bb + y * fb.width, fb.width * 4);
    }
}
